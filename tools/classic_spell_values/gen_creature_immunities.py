# Writes the vanilla (VMaNGOS 1.12) school and mechanic immunities of the creatures that have any, as sql/custom/world rows:
#   python3 -I gen_creature_immunities.py > ../../sql/custom/world/2026_10_11_03_world_classic_creature_immunities.sql
# Each such creature gets its own creature_immunities row (ID 5,000,000 + entry): the VMaNGOS school_immune_mask and mechanic_immune_mask, with the
# dispel / effect / aura / area / chain parts of the creature's current immunity row kept. Vanilla mechanic bit n is mechanic n + 1 (the mechanic
# numbers equal the client's up to 31). Safe to run again.
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import compare_creatures as c

SRC = os.environ.get('VMANGOS_SRC') or os.path.join(os.path.dirname(os.path.abspath(__file__)), 'data', 'vmangos_extract.sql.gz')
BASE_ID = 5000000


def main():
    v = c.load_vanilla(SRC)
    rows = []
    for e in sorted(v):
        r = v[e]
        school = int(r.get('school_immune_mask') or 0) & 0x7F
        vm = int(r.get('mechanic_immune_mask') or 0)
        mech = 0
        for i in range(31):                       # vanilla bit i -> mechanic i + 1 (bit 31 has no mechanic)
            if vm >> i & 1:
                mech |= 1 << (i + 1)
        if school or mech:
            rows.append((e, school, mech))
    out = ['-- Classic 1.60: vanilla (VMaNGOS 1.12) school and mechanic immunities of the creatures that have any (a row of their own, ID %d + entry).' % BASE_ID,
           '-- Generated by tools/classic_spell_values/gen_creature_immunities.py. Safe to run again.',
           'DROP TEMPORARY TABLE IF EXISTS `tmp_classic_immunity`;',
           'CREATE TEMPORARY TABLE `tmp_classic_immunity` (`entry` int unsigned NOT NULL PRIMARY KEY, `school` tinyint unsigned NOT NULL, `mech` bigint unsigned NOT NULL);']
    for i in range(0, len(rows), 500):
        out.append('INSERT INTO `tmp_classic_immunity` (`entry`,`school`,`mech`) VALUES')
        out.append(',\n'.join('(%d,%d,%d)' % t for t in rows[i:i + 500]) + ';')
    out.append('REPLACE INTO `creature_immunities` (`ID`,`SchoolMask`,`DispelTypeMask`,`MechanicsMask`,`Effects`,`Auras`,`ImmuneAoE`,`ImmuneChain`,`Comment`)\n'
               'SELECT %d + m.`entry`, m.`school`, COALESCE(i.`DispelTypeMask`, 0), m.`mech`, COALESCE(i.`Effects`, \'\'), COALESCE(i.`Auras`, \'\'), COALESCE(i.`ImmuneAoE`, 0), COALESCE(i.`ImmuneChain`, 0), CONCAT(\'vanilla \', t.`name`)\n'
               'FROM `tmp_classic_immunity` m JOIN `creature_template` t ON t.`entry` = m.`entry`\n'
               'LEFT JOIN `creature_immunities` i ON i.`ID` = IF(t.`CreatureImmunitiesId` BETWEEN %d AND %d, %d + t.`entry`, t.`CreatureImmunitiesId`);' % (BASE_ID, BASE_ID, BASE_ID + 999999, BASE_ID))
    out.append('UPDATE `creature_template` t JOIN `tmp_classic_immunity` m ON m.`entry` = t.`entry` SET t.`CreatureImmunitiesId` = %d + t.`entry`;' % BASE_ID)
    out.append('DROP TEMPORARY TABLE `tmp_classic_immunity`;')
    sys.stdout.write('\n'.join(out) + '\n')
    sys.stderr.write('creatures with vanilla immunities: %d\n' % len(rows))


main()
