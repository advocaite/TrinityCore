# Writes src/modules/PlayerbotV2/Diagnostics/SpellCheckExpected.inc: for every spell a class trainer teaches (the trainer lists of sql/custom/world) that is
# also a vanilla spell, the VMaNGOS 1.12 inputs of each effect value (base points, die sides, per level terms, level limits). `.playerbot spellcheck`
# evaluates the vanilla formula at the caster's level and compares it with what the core computes for the same effect.
#   python3 -I gen_spellcheck_expected.py > ../../src/modules/PlayerbotV2/Diagnostics/SpellCheckExpected.inc
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import vanilla_spells as v

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'sql', 'custom', 'world')
FILES = ['2026_10_15_00_world_classic_class_trainers.sql', '2026_10_01_04_world_forever_sniff_npc.sql',
         '2026_10_16_03_world_classic_priest_racial_ranks.sql', '2026_10_16_08_world_classic_druid_cat_ranks.sql']
# class trainer ids (full list and starting zones) -> ChrClasses id
TRAINERS = {23: 1, 22: 1, 29: 2, 28: 2, 20: 3, 19: 3, 26: 4, 25: 4, 8: 5, 7: 5, 10: 7, 11: 7, 1: 8, 5: 8, 14: 9, 13: 9, 17: 11, 1233: 11}
TUPLE = re.compile(r"^\((\d+), ?(\d+), ?(\d+), ?(\d+), ?(\d+), ?(\d+), ?(\d+), ?(\d+), ?(\d+), ?(\d+)\)", re.M)

ix, best = v.load()
spells = {}
for name in FILES:
    with open(os.path.join(ROOT, name), encoding='utf-8', errors='replace') as fh:
        text = fh.read()
    for m in TUPLE.finditer(text):
        tid, sid = int(m.group(1)), int(m.group(2))
        if tid in TRAINERS and sid in best:
            spells[sid] = TRAINERS[tid]

print('// Generated by tools/classic_spell_values/gen_spellcheck_expected.py from the VMaNGOS 1.12 spell table (GPL-2.0) and the class trainer lists. Do not edit.')
print('// { class, spell, effect index, effect, aura, base points, die sides, dice per level, points per level, base level, max level, spell level }')
for sid in sorted(spells):
    _, f, _ = best[sid]
    g = lambda c: float(f[ix[c]]) if '.' in str(f[ix[c]]) else int(f[ix[c]])
    for i in (1, 2, 3):
        eff = g('effect%d' % i)
        if not eff:
            continue
        print('{ %d, %d, %d, %d, %d, %d, %d, %.4ff, %.4ff, %d, %d, %d },' % (
            spells[sid], sid, i - 1, eff, g('effectApplyAuraName%d' % i), g('effectBasePoints%d' % i), g('effectDieSides%d' % i),
            g('effectDicePerLevel%d' % i), g('effectRealPointsPerLevel%d' % i), g('baseLevel'), g('maxLevel'), g('spellLevel')))
