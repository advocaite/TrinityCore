# Writes the vanilla (VMaNGOS 1.12) level rule of the summon spells for sql/custom/world from the extract of the VMaNGOS dump (extract-vmangos.ps1, or the
# whole dump through VMANGOS_SRC), spell_template row of the highest build <= 5875:
#   python3 -I gen_summon_levels.py > ../../sql/custom/world/2026_10_27_40_world_classic_summon_level.sql
# spell_classic_summon_level: the spells whose creature cast summons at the caster's level plus level_offset (VMaNGOS Spell::EffectSummon, EffectSummonPet,
# EffectSummonGuardian with effectMultipleValue <= 0, EffectSummonTotem, EffectSummonDemon). TempSummon::InitStats uses it for creature summoners, where the
# creature_classic_level row of the summoned creature would otherwise fix its level (Twilight Shadowmage level 26 summoning a level 47 Voidwalker Minion).
# Spells without a row keep the summoned creature's own level (SUMMON_WILD, guardians with a positive effectMultipleValue). Safe to run again.
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import vanilla_spells as v

CASTER_LEVEL = (28, 56, 74, 87, 88, 89, 90, 112)   # SUMMON, SUMMON_PET, SUMMON_TOTEM, SUMMON_TOTEM_SLOT1-4, SUMMON_DEMON
GUARDIAN = 42                                       # SUMMON_GUARDIAN
PET = 56
MAX_LEVEL = 63                                      # VMaNGOS CREATURE_MAX_LEVEL


def main():
    ix, best = v.load()
    rows = []
    mixed = []
    for s in sorted(best):
        f = best[s][1]
        offsets = []
        for i in (1, 2, 3):
            e = int(f[ix['effect%d' % i]])
            mv = float(f[ix['effectMultipleValue%d' % i]])
            if e in CASTER_LEVEL:
                offsets.append(int(mv) if e == PET else 0)
            elif e == GUARDIAN and -MAX_LEVEL < mv <= 0:
                offsets.append(int(mv))
            elif e == GUARDIAN:
                # positive, or so far below zero (city guards -1e17) that no caster level stays above 0: the creature's own level
                offsets.append(None)
        if not offsets or offsets[0] is None:
            continue
        if len(set(offsets)) > 1:
            mixed.append(s)
        if not -MAX_LEVEL < offsets[0] <= 0:
            raise SystemExit('spell %d: level offset %d out of range' % (s, offsets[0]))
        rows.append('(%d,%d)' % (s, offsets[0]))
    out = ['-- Classic 1.60: vanilla (VMaNGOS 1.12, world_full_14_june_2021, highest build <= 5875) level of the creatures a creature summons by spell:',
           '-- the caster level plus level_offset. Generated by tools/classic_spell_values/gen_summon_levels.py. Safe to run again.',
           'CREATE TABLE IF NOT EXISTS `spell_classic_summon_level` (',
           '  `spell_id` int unsigned NOT NULL, `level_offset` tinyint NOT NULL DEFAULT 0,',
           '  PRIMARY KEY (`spell_id`)',
           ') ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT=\'Classic 1.60: summon spells whose creature cast summons at the caster level (VMaNGOS)\';',
           'DELETE FROM `spell_classic_summon_level`;']
    for i in range(0, len(rows), 500):
        out.append('REPLACE INTO `spell_classic_summon_level` (`spell_id`,`level_offset`) VALUES')
        out.append(',\n'.join(rows[i:i + 500]) + ';')
    sys.stdout.write('\n'.join(out) + '\n')
    sys.stderr.write('spells: %d, with effects of different rules (first effect taken): %s\n' % (len(rows), mixed))


main()
