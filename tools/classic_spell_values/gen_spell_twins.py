# Forever's client ships its own copies ("twins") of many vanilla player spells under ids that the VMaNGOS dump does not have (Drain Life rank 6 is 403689, the
# vanilla one 11700): they keep the client's cooldown, duration and mana cost. A twin is a spell of SpellAudit.tsv that is not in the dump, whose name, spell level
# and effect/aura/misc of all three effects equal those of exactly one VMaNGOS player spell (a spell with a family and a level). Anything less certain is listed
# in the report, not guessed. Output: sql/custom/world file with table classic_spell_twin and the twin's rows of classic_spell_info / _cost / _value:
#   python3 -I gen_spell_twins.py --audit SpellAudit.tsv --extract data/vmangos_extract.sql.gz --dbc vanilla-dbc --report twins.md \
#       > ../../sql/custom/world/2026_10_11_06_world_classic_spell_twins.sql
# Safe to run again.
import argparse, collections, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import vanilla_spells as v
import compare_spells as cs
from gen_spell_info import CAST_TOL, TIME_TOL, RANGE_TOL, MELEE_RANGE, KEEP_CLIENT_DURATION, KEEP_CLIENT_CAST, KEEP_CLIENT_COOLDOWN, \
    KEEP_CLIENT_RANGE, KEEP_CLIENT_COST, KEEP_CLIENT_VALUE, esc

FIRST_SCALED = 1000000     # ClassicSpellValue::FirstScaledSpellId: from here on the spells are not legacy ones
# Drain Life 403677-403689: the 70532 spell is a 15 s drain that is not channeled, not a twin of the vanilla channel
NOT_TWINS = {403677, 403685, 403686, 403687, 403688, 403689}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--audit', required=True)
    ap.add_argument('--extract', default=os.path.join(HERE, 'data', 'vmangos_extract.sql.gz'))
    ap.add_argument('--dbc', required=True)
    ap.add_argument('--report')
    a = ap.parse_args()
    ix, best = v.load(a.extract)
    audit = cs.read_audit(a.audit)
    dbc = cs.load_dbc(a.dbc)
    g = lambda f, c: float(f[ix[c]]) if f[ix[c]].upper() != 'NULL' else 0.0
    players = collections.defaultdict(list)       # lower case name -> vanilla player spell ids
    for e, (_, f, n) in best.items():
        if g(f, 'spellFamilyName') != 0 and g(f, 'spellLevel') > 0:
            players[n.lower()].append(e)
    sig_v = lambda f: tuple((int(g(f, 'effect%d' % i)), int(g(f, 'effectApplyAuraName%d' % i)), int(g(f, 'effectMiscValue%d' % i))) for i in (1, 2, 3))
    sig_a = lambda r: tuple((int(r['e%d_effect' % i]), int(r['e%d_aura' % i]), int(r['e%d_misc' % i])) for i in (1, 2, 3))
    twins, ambiguous, unmatched = {}, [], []
    for t in sorted(audit):
        if t in best or t >= FIRST_SCALED or t in NOT_TWINS:
            continue
        r = audit[t]
        n = r['name'].lower()
        if n not in players:
            continue
        lv = int(r['spell_level'])
        cand = [x for x in players[n] if int(g(best[x][1], 'spellLevel')) == lv and sig_v(best[x][1]) == sig_a(r)]
        if len(cand) == 1:
            twins[t] = cand[0]
        elif cand:
            ambiguous.append((t, r['name'], lv, cand))
        elif lv > 1:
            unmatched.append((t, r['name'], lv))
    num = lambda f, col: g(f, col)
    rows = []
    for t, vid in sorted(twins.items()):
        _, f, name = best[vid]
        c = audit[t]
        cast = dbc['cast'].get(int(num(f, 'castingTimeIndex')), 0)
        rec, cat = int(num(f, 'recoveryTime')), int(num(f, 'categoryRecoveryTime'))
        dur = dbc['dur'].get(int(num(f, 'durationIndex')))
        rng = dbc['range'].get(int(num(f, 'rangeIndex')), 0.0)
        norm = lambda d: 0 if d is None or d <= 0 else d
        o = {}
        if t not in KEEP_CLIENT_CAST and abs(cast - int(c['cast_ms'])) > CAST_TOL: o['cast_ms'] = cast
        if t not in KEEP_CLIENT_COOLDOWN and abs(rec - int(c['recovery_ms'])) > TIME_TOL: o['recovery_ms'] = rec
        if t not in KEEP_CLIENT_COOLDOWN and abs(cat - int(c['category_recovery_ms'])) > TIME_TOL: o['category_recovery_ms'] = cat
        if dur is not None and t not in KEEP_CLIENT_DURATION and norm(dur) != norm(int(c['duration_ms'])): o['duration_ms'] = dur
        if t not in KEEP_CLIENT_RANGE and rng > MELEE_RANGE and abs(rng - float(c['range_max'])) > RANGE_TOL: o['range_max'] = rng
        rows.append((t, vid, name, o, int(num(f, 'manaCost')), int(num(f, 'manaCostPercentage'))))
    cols = ('cast_ms', 'recovery_ms', 'category_recovery_ms', 'duration_ms', 'range_max')
    fmt = lambda x: 'NULL' if x is None else (repr(float(x)) if isinstance(x, float) else str(x))
    s = ['-- Classic 1.60: Forever twins of vanilla player spells (same name, spell level and effects as exactly one VMaNGOS spell, a different spell id) take the',
         '-- vanilla spell\'s cast time, cooldowns, duration, range, mana cost and effect values. Generated by tools/classic_spell_values/gen_spell_twins.py. Safe to run again.',
         'CREATE TABLE IF NOT EXISTS `classic_spell_twin` (`spell_id` int unsigned NOT NULL, `vanilla_spell_id` int unsigned NOT NULL, `spell_name` varchar(100) NOT NULL DEFAULT \'\', PRIMARY KEY (`spell_id`)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;',
         'DELETE FROM `classic_spell_twin`;']
    for i in range(0, len(rows), 500):
        s.append('INSERT INTO `classic_spell_twin` (`spell_id`,`vanilla_spell_id`,`spell_name`) VALUES')
        s.append(',\n'.join("(%d,%d,'%s')" % (t, vid, esc(n)) for t, vid, n, _, _, _ in rows[i:i + 500]) + ';')
    info = [r for r in rows if r[3]]
    s.append('DELETE FROM `classic_spell_info` WHERE `spell_id` IN (SELECT `spell_id` FROM `classic_spell_twin`);')
    for i in range(0, len(info), 500):
        s.append('INSERT INTO `classic_spell_info` (`spell_id`,`cast_ms`,`recovery_ms`,`category_recovery_ms`,`duration_ms`,`range_max`,`radius1`,`radius2`,`radius3`,`spell_name`) VALUES')
        s.append(',\n'.join("(%d,%s,NULL,NULL,NULL,'%s')" % (t, ','.join(fmt(o.get(k)) for k in cols), esc(n)) for t, _, n, o, _, _ in info[i:i + 500]) + ';')
    s.append('DELETE FROM `classic_spell_cost` WHERE `spell_id` IN (SELECT `spell_id` FROM `classic_spell_twin`);')
    for i in range(0, len(rows), 500):
        s.append('INSERT INTO `classic_spell_cost` (`spell_id`,`mana_cost`,`mana_cost_pct`,`spell_name`) VALUES')
        s.append(',\n'.join("(%d,%d,%d,'%s')" % (t, m, p, esc(n)) for t, _, n, _, m, p in rows[i:i + 500] if t not in KEEP_CLIENT_COST) + ';')
    s.append('DELETE FROM `classic_spell_value` WHERE `spell_id` IN (SELECT `spell_id` FROM `classic_spell_twin`);')
    s.append('INSERT INTO `classic_spell_value` (`spell_id`,`effect_index`,`effect`,`apply_aura`,`base_points`,`die_sides`,`points_per_level`,`misc_value`,`points_per_combo`,`bonus_coeff`,`spell_name`)\n'
             'SELECT w.`spell_id`, x.`effect_index`, x.`effect`, x.`apply_aura`, x.`base_points`, x.`die_sides`, x.`points_per_level`, x.`misc_value`, x.`points_per_combo`, x.`bonus_coeff`, x.`spell_name`\n'
             'FROM `classic_spell_twin` w JOIN `classic_spell_value` x ON x.`spell_id` = w.`vanilla_spell_id`;')
    keep = [(t, i) for t, i in sorted(KEEP_CLIENT_VALUE) if t in twins]
    if keep:
        s.append('DELETE FROM `classic_spell_value` WHERE (`spell_id`, `effect_index`) IN (%s);' % ', '.join('(%d, %d)' % k for k in keep))
    sys.stdout.write('\n'.join(s) + '\n')
    if a.report:
        with open(a.report, 'w') as fh:
            fh.write('# Forever twins of vanilla player spells\n\nMapped: %d (changed fields: %d spells). Ambiguous: %d. Same name, no match: %d.\n\n' % (len(rows), len(info), len(ambiguous), len(unmatched)))
            fh.write('## Mapped (twin -> vanilla, changed fields)\n| twin | vanilla | name | changes |\n|---|---|---|---|\n')
            for t, vid, n, o, m, p in rows:
                fh.write('| %d | %d | %s | %s |\n' % (t, vid, n, ', '.join('%s=%s' % kv for kv in sorted(o.items())) or '-'))
            fh.write('\n## Ambiguous (not mapped)\n| spell | name | level | vanilla candidates |\n|---|---|---|---|\n')
            for t, n, lv, c in ambiguous:
                fh.write('| %d | %s | %d | %s |\n' % (t, n, lv, ', '.join(map(str, c))))
            fh.write('\n## Same name as a vanilla player spell but no level/effect match (not mapped)\n| spell | name | level |\n|---|---|---|\n')
            for t, n, lv in unmatched:
                fh.write('| %d | %s | %d |\n' % (t, n, lv))
    sys.stderr.write('twins %d, with info changes %d, ambiguous %d, unmatched %d\n' % (len(rows), len(info), len(ambiguous), len(unmatched)))


if __name__ == '__main__':
    main()
