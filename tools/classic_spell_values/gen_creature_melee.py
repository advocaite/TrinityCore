# Writes the vanilla (VMaNGOS 1.12) melee numbers of every creature for sql/custom/world from the extract of the VMaNGOS dump (extract-vmangos.ps1, or the
# whole dump through VMANGOS_SRC), creature_template row of the highest patch <= 10:
#   python3 -I gen_creature_melee.py > ../../sql/custom/world/2026_10_11_01_world_classic_creature_melee.sql
# creature_classic_melee: the hit per swing (dmg_min / dmg_max x dmg_multiplier) and the swing times. Creature::CalculateMinMaxDamage and UpdateEntry use them
# instead of the client's damage per second table x the old damage modifiers x the swing time. Safe to run again.
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import compare_creatures as c

SRC = os.environ.get('VMANGOS_SRC') or os.path.join(os.path.dirname(os.path.abspath(__file__)), 'data', 'vmangos_extract.sql.gz')


def main():
    v = c.load_vanilla(SRC)
    rows = []
    for e in sorted(v):
        r = v[e]
        if r.get('dmg_max') is None:
            continue
        m = r.get('dmg_multiplier') or 1.0
        rows.append('(%d,%.2f,%.2f,%d,%d)' % (e, (r['dmg_min'] or 0) * m, (r['dmg_max'] or 0) * m, int(r.get('base_attack_time') or 0), int(r.get('ranged_attack_time') or 0)))
    out = ['-- Classic 1.60: vanilla (VMaNGOS 1.12, world_full_14_june_2021, highest patch row <= 10) melee hit and swing time of every creature.',
           '-- Generated by tools/classic_spell_values/gen_creature_melee.py. Safe to run again.',
           'CREATE TABLE IF NOT EXISTS `creature_classic_melee` (',
           '  `entry` int unsigned NOT NULL, `dmg_min` float NOT NULL, `dmg_max` float NOT NULL, `attack_ms` int unsigned NOT NULL, `ranged_attack_ms` int unsigned NOT NULL,',
           '  PRIMARY KEY (`entry`)',
           ') ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;',
           'DELETE FROM `creature_classic_melee`;']
    for i in range(0, len(rows), 500):
        out.append('INSERT INTO `creature_classic_melee` (`entry`,`dmg_min`,`dmg_max`,`attack_ms`,`ranged_attack_ms`) VALUES')
        out.append(',\n'.join(rows[i:i + 500]) + ';')
    # the creature's rank (0 normal, 1 elite, 2 rare elite, 3 boss, 4 rare): retail has Ragnaros as an elite, vanilla as a boss
    out.append('-- creature_template.`Classification` (the vanilla rank) of the vanilla creatures (only rows that differ are touched)')
    by_rank = {}
    for e in sorted(v):
        r = v[e]
        if r.get('rank') is not None and int(r['rank']) in (0, 1, 2, 3, 4):
            by_rank.setdefault(int(r['rank']), []).append(e)
    for rk, ents in sorted(by_rank.items()):
        for i in range(0, len(ents), 1000):
            out.append('UPDATE `creature_template` SET `Classification` = %d WHERE `Classification` <> %d AND `entry` IN (%s);' % (rk, rk, ','.join(map(str, ents[i:i + 1000]))))
    sys.stdout.write('\n'.join(out) + '\n')
    sys.stderr.write('creatures: %d\n' % len(rows))


main()
