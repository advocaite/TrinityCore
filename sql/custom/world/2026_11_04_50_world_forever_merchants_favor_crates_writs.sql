-- Waylaid Crate 248549 -> Read Label 1247168 -> a labeled crate (30 kinds) -> Stock Crate with one bundle -> a Sealed crate to hand in.
-- Sealed writ -> Open Letter -> a Craftsman's Writ that starts its own order quest.
-- Source: the 70685 client data (Spell, SpellEffect, ItemSalvageLoot, ItemSparse). The bundles are the Stock Crate spell's text
-- ($M3 Peacebloom ...) with the counts of its dummy effects; the items are the client's own ids from its ItemSalvage list 124.
-- The writ tiers are ItemSalvageLoot list 244 (loot 134598 Journeyman, 134599 Expert, 134600 Artisan = the Open Letter loot ids).
-- NOT from live data yet: the chance of each labeled crate and of each Sealed crate quality (white / green / blue). Until the
-- live rates are known: every labeled crate and every writ is equally likely, and a stocked crate is 70% white, 25% green, 5% blue.
-- Safe to run again.

