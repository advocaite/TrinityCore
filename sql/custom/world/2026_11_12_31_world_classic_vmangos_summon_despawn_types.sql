-- Summon despawn types from the VMaNGOS script conversion (follow-up to One Shot. One Kill., 2026_11_12_30).
-- The converter that turned VMaNGOS scripts (EventAI, quest_start/quest_end/generic/creature_movement/gossip scripts) into
-- SmartAI summons (SMART_ACTION_SUMMON_CREATURE, 12) did not copy the despawn type (VMaNGOS dataint4). It wrote type 3
-- (TEMPSUMMON_TIMED_DESPAWN: gone after the time even in the middle of a fight) when the script had a despawn time, and 8 (manual)
-- when it had none. VMaNGOS mostly uses type 1: the time only counts while the creature is out of combat. So escort ambushers,
-- quest event waves and called guards vanished mid-fight, and event bosses that must die to finish a quest could vanish first.
-- Each converted row names its VMaNGOS script (comment "VMaNGOS <table> <id>"). It was matched against the public VMaNGOS world
-- database (brotalnia/database world_full_14_june_2021) plus every vmangos/core world migration after it, by script id, summoned
-- creature and summon position, and the despawn time was checked to be the same on both sides. VMaNGOS and TrinityCore number
-- these types the same way (1 timed or dead, 2 timed or corpse, 4 timed out of combat, 5 corpse, 7 dead).
-- Changed: 214 rows. Each UPDATE only touches a row that still summons the same creature with the old converted type.
-- Not changed here:
--   * 93 rows that VMaNGOS summons with type 4 or 2 and no time, attacking the summoner's target (flight master Enraged
--     Gryphons and Wyverns, a few guards). With no attack on summon those types would despawn them at once; the converted rows
--     have no attack and the creatures despawn by their own SmartAI out of combat. Needs the attack carried over first.
--   * 35 rows of the Counterattack event (generic_scripts 402110), manual despawn in VMaNGOS, ended by its map event.
--   * 8 rows of One Shot. One Kill. (2026_11_12_30) and 5 rows with no VMaNGOS match.
-- Safe to run again.

