-- Camping 101 profession quests missing from the data for the Elwynn Forest hub (Sam Sarsaparilla, after The Great Outdoors
-- 95998), the Dun Morogh hub (Eric Brighthammer, after 96608) and the Tirisfal Glades hub (Eleanor Shackleton, after 96607).
-- The Forever quest list has them (level 6, req 4); Elwynn had only Cooking/Herbalism/Mining/Tailoring, Dun Morogh only
-- Tailoring and Tirisfal no Alchemy/Blacksmithing/Engineering/Leatherworking/Mining, so those were never offered.
-- Elwynn Skinning (97924) is in 2026_10_26_27.
-- Each quest is built from the same profession's quest of another hub (Shen'dar, Tirisfal or Elwynn): text and turn-in text
-- where it has them, objective and reward spell. Level 6, required 4 come from the Forever quest list; giver, prerequisite
-- and "profession skill 1" come from the hub, as its existing quests have them.
-- Objective criteria trees come from the 70532 CriteriaTree.db2 ("Camp Training - Raise <profession> to 20+", one per quest:
-- Elwynn 231064-231086, Dun Morogh 227798-227818, Tirisfal 231134-231154); each quest needs its own tree because the core
-- maps one objective per tree.
-- Engineering's reward is 1255261 "Reagent Bot" (70532 SpellName); no Engineering copy exists, so its text is written here.
-- INFERRED: the turn-in NPCs. The existing copies turn in at the nearest classic trainer of the profession, so these use the
-- nearest spawned trainer that teaches the apprentice rank (creature_trainer); Tirisfal's existing quests turn in at Brill
-- trainers, so Alchemy and Leatherworking use the Brill ones (Carolai Anise, Shelene Rhobart). The Dun Morogh Cooking tree
-- (227854) is the first unused "Learn cooking" tree. Check against the quest pages when they are fetched.


